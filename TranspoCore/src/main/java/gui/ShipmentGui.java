    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String sender = txtSenderName.getText();
        String receiver = txtReceiverName.getText();
        String contents = txtPackageContents.getText();
        String status = jComboBox1.getSelectedItem().toString();
        String email = txtSenderEmail.getText();
        String date = jTextField1.getText();
        String weightStr = txtWeight.getText();
        String address = txtDeliveryAddress.getText();

        if (sender.isEmpty() || receiver.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Sender and Receiver names are required.");
            return;
        }

        try {
            double weight = Double.parseDouble(weightStr);

            Shipment shipment = new Shipment();  // this is your model now
            shipment.setSenderName(sender);
            shipment.setReceiverName(receiver);
            shipment.setPackageContents(contents);
            shipment.setDeliveryStatus(status);
            shipment.setSenderEmail(email);
            shipment.setShipmentDate(date);
            shipment.setWeight(weight);
            shipment.setDeliveryAddress(address);

            boolean success = shipmentService.addShipment(shipment);

            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Shipment added and email sent.");
                loadShipmentsToTable();
                clearForm();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to add shipment.");
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid weight format.");
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int selectedRow = tblShipments.getSelectedRow();

        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a shipment to update.");
            return;
        }

        // Get shipment ID from the first column of the selected row
        int shipmentId = Integer.parseInt(txtShipmentId.getText());
        String sender = txtSenderName.getText();
        String receiver = txtReceiverName.getText();
        String contents = txtPackageContents.getText();
        String status = jComboBox1.getSelectedItem().toString();
        String email = txtSenderEmail.getText();
        String date = jTextField1.getText();
        String weightStr = txtWeight.getText();
        String address = txtDeliveryAddress.getText();

        if (sender.isEmpty() || receiver.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Sender and Receiver names are required.");
            return;
        }

        try {
            double weight = Double.parseDouble(weightStr);

            Shipment shipment = new Shipment();
            shipment.setShipmentId(shipmentId);
            shipment.setSenderName(sender);
            shipment.setReceiverName(receiver);
            shipment.setPackageContents(contents);
            shipment.setDeliveryStatus(status);
            shipment.setSenderEmail(email);
            shipment.setShipmentDate(date);
            shipment.setWeight(weight);
            shipment.setDeliveryAddress(address);

            boolean success = shipmentService.updateShipment(shipment);

            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Shipment updated successfully.");
                loadShipmentsToTable();
                clearForm();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Failed to update shipment.");
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid weight format.");
        }// TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = tblShipments.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a shipment to delete.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this shipment?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int shipmentId = Integer.parseInt(tblShipments.getValueAt(selectedRow, 0).toString());

            boolean success = shipmentService.deleteShipment(shipmentId);

            if (success) {
                JOptionPane.showMessageDialog(this, "Shipment deleted successfully.");
                loadShipmentsToTable();
                clearForm();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete shipment.");
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "An error occurred while deleting the shipment.");
        }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

