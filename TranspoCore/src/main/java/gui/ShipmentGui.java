    private void loadShipmentsToTable() {
        java.util.List<Shipment> list = shipmentService.getAllShipments();
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblShipments.getModel();
        model.setRowCount(0); // clear table

        for (Shipment s : list) {
            model.addRow(new Object[]{
                s.getShipmentId(),
                s.getSenderName(),
                s.getReceiverName(),
                s.getPackageContents(),
                s.getDeliveryStatus(),
                s.getSenderEmail(),
                s.getShipmentDate(),
                s.getWeight(),
                s.getDeliveryAddress()
            });
        }
    }
